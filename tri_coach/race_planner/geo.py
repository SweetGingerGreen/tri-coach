def _strip(name: str | None) -> str:
    return re.sub(r"(特别行政区|自治区|省|市|区|县)$", "", (name or "").strip())


def locate(province: str | None, city: str | None, lat: float | None = None,
           lng: float | None = None) -> tuple[tuple[float, float] | None, str]:
    """Best coordinate for a place and how it was found: coords / city / province / none."""
    if lat and lng:
        return (float(lat), float(lng)), "coords"
    text = f"{city or ''}"
    for name in sorted(CITIES, key=len, reverse=True):
        if name in text:
            return CITIES[name], f"city:{name}"
    province_key = _strip(province)
    for name, point in PROVINCE_CAPITALS.items():
        if province_key and province_key.startswith(name):
            return point, f"province:{name}"
    return None, "none"


def km(a: tuple[float, float], b: tuple[float, float]) -> float:
    lat1, lng1, lat2, lng2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lng2 - lng1) / 2) ** 2
    return 2 * 6371.0 * math.asin(math.sqrt(h))


def same_city(home_city: str | None, race_city: str | None) -> bool:
    home = _strip(home_city)
    return bool(home) and home in (race_city or "")
